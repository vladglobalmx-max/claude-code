import { describe, expect, it } from "vitest";
import {
  providerLabel,
  translateOrientation,
  translateSurfaceMaterial,
  translateSurfaceType,
  translateUnit,
  translateUse,
  translateOrderStatus,
  translateDate,
} from "./provider-i18n";

describe("providerLabel (THÖREN — Adenda PDF Pedido, idioma para Proveedor)", () => {
  it("en español devuelve exactamente el label existente, sin cambio visual", () => {
    expect(providerLabel("date", "es")).toBe("Fecha");
    expect(providerLabel("orderNumber", "es")).toBe("No. de pedido");
    expect(providerLabel("generatedByThoren", "es")).toBe("Generado por THÖREN");
  });

  it("en inglés traduce las etiquetas fijas del documento", () => {
    expect(providerLabel("date", "en")).toBe("Date");
    expect(providerLabel("orderNumber", "en")).toBe("Order No.");
    expect(providerLabel("generatedByThoren", "en")).toBe("Generated by THÖREN");
  });

  it("cubre las etiquetas clave del pedido (proveedor, productos, instalación)", () => {
    expect(providerLabel("supplier", "en")).toBe("Supplier");
    expect(providerLabel("products", "en")).toBe("Products");
    expect(providerLabel("installation", "en")).toBe("Installation");
    expect(providerLabel("imageToProject", "en")).toBe("Image to project");
    expect(providerLabel("lensPendingFactory", "en")).toBe("To be defined with factory");
  });
});

