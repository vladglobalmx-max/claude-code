describe("translateUnit", () => {
  it("en español nunca cambia la unidad", () => {
    expect(translateUnit("pies", "es")).toBe("pies");
    expect(translateUnit("m", "es")).toBe("m");
  });

  it('en inglés traduce "pies" a "ft"; m/cm no cambian por ser ya neutrales', () => {
    expect(translateUnit("pies", "en")).toBe("ft");
    expect(translateUnit("m", "en")).toBe("m");
    expect(translateUnit("cm", "en")).toBe("cm");
  });

  it("una unidad desconocida se devuelve sin cambios (nunca inventa una traducción)", () => {
    expect(translateUnit("in", "en")).toBe("in");
  });
});

describe("translateOrderStatus", () => {
  it("en español devuelve el label ya existente tal cual (passthrough)", () => {
    expect(translateOrderStatus("pedido", "es", "Pedido")).toBe("Pedido");
  });

  it("traduce los 4 estados fijos del enum en inglés", () => {
    expect(translateOrderStatus("borrador", "en", "Borrador")).toBe("Draft");
    expect(translateOrderStatus("pedido", "en", "Pedido")).toBe("Order");
    expect(translateOrderStatus("cerrado", "en", "Cerrado")).toBe("Closed");
    expect(translateOrderStatus("cancelado", "en", "Cancelado")).toBe("Cancelled");
  });

  it("un estado desconocido cae al label español dado, nunca inventa una traducción", () => {
    expect(translateOrderStatus("desconocido", "en", "Desconocido")).toBe("Desconocido");
  });
});

describe("translateDate", () => {
  it("en español devuelve el texto ya formateado tal cual (passthrough, sin tocar formatDate)", () => {
    expect(translateDate("2026-10-09", "es", "9 de octubre 2026")).toBe("9 de octubre 2026");
  });

  it("en inglés formatea la fecha con nombre de mes en inglés, nunca en español", () => {
    expect(translateDate("2026-10-09", "en", "9 de octubre 2026")).toBe("October 9, 2026");
  });
});
