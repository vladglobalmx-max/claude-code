/**
 * Traduce el VALOR de un enum legacy (piso/pared/interior/...) — nunca
 * texto libre. En español devuelve exactamente el label ya existente
 * (ver ORIENTATION_LABELS/USE_LABELS/SURFACE_TYPE_LABELS/
 * SURFACE_MATERIAL_LABELS de types/domain.ts) — cero cambio visual para
 * el documento en español.
 */
export function translateOrientation(value: Orientation, language: ProviderDocumentLanguage, spanishLabel: string): string {
  return language === "en" ? ORIENTATION_LABELS_EN[value] : spanishLabel;
}

export function translateUse(value: UseEnvironment, language: ProviderDocumentLanguage, spanishLabel: string): string {
  return language === "en" ? USE_LABELS_EN[value] : spanishLabel;
}

export function translateSurfaceType(value: SurfaceType, language: ProviderDocumentLanguage, spanishLabel: string): string {
  return language === "en" ? SURFACE_TYPE_LABELS_EN[value] : spanishLabel;
}

export function translateSurfaceMaterial(value: SurfaceMaterial, language: ProviderDocumentLanguage, spanishLabel: string): string {
  return language === "en" ? SURFACE_MATERIAL_LABELS_EN[value] : spanishLabel;
}

const UNIT_LABEL_EN: Record<string, string> = { m: "m", cm: "cm", pies: "ft" };

/** Unidad de medida (m/cm/pies) — "pies" es la única que cambia en inglés ("ft"); m/cm ya son neutrales. */
export function translateUnit(unit: string, language: ProviderDocumentLanguage): string {
  if (language !== "en") return unit;
  return UNIT_LABEL_EN[unit] ?? unit;
}

const ORDER_STATUS_LABELS_EN: Record<string, string> = {
  borrador: "Draft",
  pedido: "Order",
  cerrado: "Closed",
  cancelado: "Cancelled",
};

/** Estado del pedido (badge) — nunca traduce nada más allá de estos 4 valores fijos del enum. */
export function translateOrderStatus(status: string, language: ProviderDocumentLanguage, spanishLabel: string): string {
  return language === "en" ? ORDER_STATUS_LABELS_EN[status] ?? spanishLabel : spanishLabel;
}

/**
 * Fecha del documento — en español usa el formato ya existente (con nombre
 * de mes en español, ver formatDate en lib/utils/format.ts, sin tocar esa
 * función compartida por el resto de la app). En inglés usa el mismo
 * formato "d MMMM yyyy" pero con locale enUS, para que un documento en
 * inglés no muestre nombres de mes en español (ej. "marzo").
 */
export function translateDate(dateStr: string, language: ProviderDocumentLanguage, spanishFormatted: string): string {
  if (language !== "en") return spanishFormatted;
  return format(parseISO(dateStr), "MMMM d, yyyy", { locale: enUS });
}
