export type ProviderLabelKey = keyof typeof LABELS;

/** Exclusivamente para pruebas — permite iterar todas las etiquetas fijas del documento sin duplicar la lista. */
export const LABELS_FOR_TESTING = LABELS;

/** Etiqueta fija del documento — nunca un dato real (cliente/proveedor/SKU/texto libre). */
export function providerLabel(key: ProviderLabelKey, language: ProviderDocumentLanguage): string {
  return LABELS[key][language];
}

